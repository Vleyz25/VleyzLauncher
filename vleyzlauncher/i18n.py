def set_language(name: str) -> str:
    global CURRENT
    CURRENT = name if name in LANGUAGES else "ru"
    return CURRENT


def language_name(name: str) -> str:
    return LANGUAGES.get(name, LANGUAGES["ru"])


def tr(value):
    """Переводит строку, если включён английский."""
    if CURRENT != "en" or not isinstance(value, str):
        return value
    exact = EN.get(value)
    if exact is not None:
        return exact
    result = value
    for pattern, replacement in _PATTERNS:
        result = pattern.sub(replacement, result)
    return result


def tf(template: str, **kwargs) -> str:
    return tr(template).format(**kwargs)
